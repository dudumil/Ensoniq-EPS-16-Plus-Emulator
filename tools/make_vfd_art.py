#!/usr/bin/env python3
"""Generates src/vfd_art.h: the ASR-10 VFD character set (15-segment masks) and the
annunciator legends rendered as 4-bit alpha bitmaps.

Usage: python3 tools/make_vfd_art.py [path/to/FreeSansBoldOblique.ttf]

The segment masks were read off photos of a real ASR-10 display (and agree with the
segment patterns of the Ensoniq ESQ-1 style VFD). The legends are typeset with GNU FreeSans
Bold Oblique, at the positions measured on a photo of the display glass.
"""
import sys, os
from PIL import Image, ImageDraw, ImageFont
sys.path.insert(0, os.path.dirname(__file__))
from vfd_layout import ROWS

FONT = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/freefont/FreeSansBoldOblique.ttf'
OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'vfd_art.h')

# ---------------------------------------------------------------- character set
SEG = {n: i for i, n in enumerate('a b c d e f g1 g2 h i j k l m dp'.split())}
CHARS = {
    ' ': '', '"': 'f i', '$': 'a c d f g1 g2 i l', '&': 'a d e f g1 i m', "'": 'j',
    '*': 'g1 g2 h i j k l m', '+': 'g1 g2 i l', ',': 'k', '-': 'g1 g2', '.': 'dp', '/': 'j k',
    '0': 'a b c d e f j k',            # the ASR-10 zero is slashed (photos); the letter O is not
    '1': 'b c', '2': 'a b d e g1 g2', '3': 'a b c d g1 g2', '4': 'b c f g1 g2', '5': 'a c d f g1 g2',
    '6': 'a c d e f g1 g2', '7': 'a b c', '8': 'a b c d e f g1 g2', '9': 'a b c d f g1 g2',
    '<': 'j m', '=': 'd g1 g2', '>': 'h k', '?': 'a b f g2 l', '@': 'a b d e f g2 i',
    'A': 'a b c e f g1 g2', 'B': 'a b c d g2 i l', 'C': 'a d e f', 'D': 'a b c d i l',
    'E': 'a d e f g1 g2', 'F': 'a e f g1 g2', 'G': 'a c d e f g2', 'H': 'b c e f g1 g2',
    'I': 'a d i l', 'J': 'b c d e', 'K': 'e f g1 j m', 'L': 'd e f', 'M': 'b c e f h j',
    'N': 'b c e f h m', 'O': 'a b c d e f', 'P': 'a b e f g1 g2', 'Q': 'a b c d e f m',
    'R': 'a b e f g1 g2 m', 'S': 'a c d f g1 g2', 'T': 'a i l', 'U': 'b c d e f', 'V': 'e f j k',
    'W': 'b c e f k m', 'X': 'h j k m', 'Y': 'h j l', 'Z': 'a d j k', '_': 'd',
}
# the character generator shows these codes as "digit + period" (OS table at $F824BE)
for d, c in zip('0123456789', '!#%():;[\\]'):
    CHARS[c] = CHARS[d] + ' dp'

def mask(s):
    m = 0
    for n in s.split(): m |= 1 << SEG[n]
    return m

# ---------------------------------------------------------------- legends
K = 26 / 90.5          # photo px -> logical px (character pitch 26)
SS = 3                 # bitmap resolution: SS texels per logical pixel
H = 13                 # legend height (logical px); boxed legends fill it
CAP = 10.0             # cap height of the lettering (logical px)
font_cache = {}

def render(text, boxed, w):
    tw, th = round(w * SS), round(H * SS)
    size = 40
    f = ImageFont.truetype(FONT, size)
    cap = f.getbbox('H')[3] - f.getbbox('H')[1]
    size = round(size * (CAP * SS) / cap)
    f = ImageFont.truetype(FONT, size)
    bb = f.getbbox(text)
    ink = Image.new('L', (bb[2] - bb[0] + 4, bb[3] - bb[1] + 4), 0)
    ImageDraw.Draw(ink).text((2 - bb[0], 2 - bb[1]), text, font=f, fill=255)
    ink = ink.crop(ink.getbbox())
    pad = round(1.3 * SS) if boxed else 0
    ink = ink.resize((tw - 2 * pad, round(CAP * SS)), Image.LANCZOS)   # fit the measured width
    img = Image.new('L', (tw, th), 0)
    if boxed:
        dr = ImageDraw.Draw(img)
        sl = round(0.16 * th)              # the boxes are slanted like the lettering
        dr.polygon([(sl, 0), (tw - 1, 0), (tw - 1 - sl, th - 1), (0, th - 1)], fill=255)
        hole = Image.new('L', img.size, 0); hole.paste(ink, (pad, (th - ink.height) // 2))
        img = Image.eval(Image.merge('L', [img]), lambda v: v)
        from PIL import ImageChops
        img = ImageChops.subtract(img, hole)
    else:
        img.paste(ink, (0, (th - ink.height) // 2))
    return img

entries, blob = [], bytearray()
row_y = [0, 14, 28]
for r, row in enumerate(ROWS):
    for text, boxed, group, index, x1, x2 in row:
        w = (x2 - x1) * K
        img = render(text, boxed, w)
        px = img.tobytes()
        off = len(blob)
        for i in range(0, len(px), 2):
            a = px[i] >> 4; b = (px[i + 1] >> 4) if i + 1 < len(px) else 0
            blob.append(a | (b << 4))
        entries.append((text, group, index, (x1 - 20) * K, row_y[r], w, H, img.width, img.height, off))

with open(OUT, 'w') as o:
    o.write('// Generated by tools/make_vfd_art.py - do not edit.\n')
    o.write('// ASR-10 VFD: 15-segment character set and annunciator legends (4-bit alpha, %dx).\n#pragma once\n#include <cstdint>\n\n' % SS)
    o.write('// segment bits: a b c d e f g1 g2 h i j k l m dp = bit 0..14 (h/j/k/m are the diagonals,\n'
            '// i/l the centre verticals, g1/g2 the middle bar halves)\n')
    o.write('static const uint16_t VFD_CHARSET[64] = {   // codes $20-$5F\n')
    for row in range(8):
        o.write('   ' + ''.join(' 0x%04x,' % mask(CHARS.get(chr(0x20 + row * 8 + i), '')) for i in range(8)) +
                '  // ' + ''.join(chr(0x20 + row * 8 + i) for i in range(8)).replace('\\', '\\\\') + '\n')
    o.write('};\n\n')
    o.write('struct VfdLegend { const char *text; int group, index; float x, y, w, h; int tw, th; uint32_t offset; };\n')
    o.write('// x/y relative to the left edge of character 0 and the top of the first legend row;\n'
            '// group 0 = panel commands $77 on / $78 off / $79 blink, group 1 = $7A / $7B / $7C\n')
    o.write('static const int VFD_ART_SCALE = %d;\n' % SS)
    o.write('static const VfdLegend VFD_LEGENDS[%d] = {\n' % len(entries))
    for e in entries:
        o.write('    { "%s", %d, 0x%x, %.2ff, %.2ff, %.2ff, %.2ff, %d, %d, %d },\n' % e)
    o.write('};\n\n')
    o.write('static const unsigned char VFD_LEGEND_ALPHA[%d] = {\n' % len(blob))
    for i in range(0, len(blob), 24):
        o.write('    ' + ''.join('%d,' % b for b in blob[i:i + 24]) + '\n')
    o.write('};\n')
print('wrote', OUT, len(entries), 'legends,', len(blob), 'bytes of alpha')
