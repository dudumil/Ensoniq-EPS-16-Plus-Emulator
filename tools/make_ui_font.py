#!/usr/bin/env python3
"""Generates src/ui_font.h: glyph atlases (GNU FreeSans / FreeSansBold) for the options page,
rendered at 2x so they stay sharp when the window is scaled up. Latin-1 (32-126, 160-255).
Usage: python3 tools/make_ui_font.py"""
import os
from PIL import Image, ImageDraw, ImageFont
D = '/usr/share/fonts/truetype/freefont/'
OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'ui_font.h')
OVERS = 2
# (name, file, logical pixel size)
FACES = [('SMALL', 'FreeSans.ttf', 11), ('BODY', 'FreeSans.ttf', 14), ('BOLD', 'FreeSansBold.ttf', 13),
         ('TITLE', 'FreeSansBold.ttf', 19)]
CODES = list(range(32, 127)) + list(range(160, 256))
out = ['// Generated by tools/make_ui_font.py - do not edit.',
       '// Options page fonts: GNU FreeSans / FreeSansBold (GPL with font exception), 4-bit alpha, 2x oversampled.',
       '#pragma once', '#include <cstdint>', '',
       'struct UiGlyph { uint16_t x, y; uint8_t w, h; int8_t ox, oy; uint8_t adv; };   // atlas pixels (2x)',
       'struct UiFace { int size, ascent, line, atlas_w, atlas_h; const UiGlyph *glyphs; const uint8_t *alpha; };', '']
for name, file, size in FACES:
    f = ImageFont.truetype(D + file, size * OVERS)
    asc, desc = f.getmetrics()
    glyphs, imgs = [], []
    for c in CODES:
        ch = chr(c)
        l, t, r, b = f.getbbox(ch)
        w, h = max(r - l, 1), max(b - t, 1)
        im = Image.new('L', (w + 2, h + 2), 0)
        ImageDraw.Draw(im).text((1 - l, 1 - t), ch, font=f, fill=255)
        adv = round(f.getlength(ch))
        imgs.append(im); glyphs.append([0, 0, w + 2, h + 2, l - 1, t - 1, adv])
    # shelf packing
    AW = 512; x = y = rowh = 0
    for g, im in zip(glyphs, imgs):
        if x + g[2] > AW: x = 0; y += rowh; rowh = 0
        g[0], g[1] = x, y; x += g[2]; rowh = max(rowh, g[3])
    AH = y + rowh
    atlas = Image.new('L', (AW, AH), 0)
    for g, im in zip(glyphs, imgs): atlas.paste(im, (g[0], g[1]))
    px = list(atlas.tobytes())
    packed = bytearray((px[i] >> 4) | (px[i + 1] & 0xf0) for i in range(0, len(px), 2))
    out.append('static const UiGlyph UI_%s_GLYPHS[] = {' % name)
    for g in glyphs: out.append('    { %d, %d, %d, %d, %d, %d, %d },' % tuple(g))
    out.append('};')
    out.append('static const uint8_t UI_%s_ALPHA[] = {' % name)
    for i in range(0, len(packed), 32): out.append('    ' + ','.join(str(v) for v in packed[i:i + 32]) + ',')
    out.append('};')
    out.append('static const UiFace UI_%s = { %d, %d, %d, %d, %d, UI_%s_GLYPHS, UI_%s_ALPHA };' % (name, size, asc, asc + desc, AW, AH, name, name))
    out.append('')
open(OUT, 'w').write('\n'.join(out) + '\n')
print('ok', OUT, os.path.getsize(OUT))
